use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    En = 0,
    Zh = 1,
    Es = 2,
    Hi = 3,
    Fr = 4,
    Ru = 5,
}

impl Lang {
    pub const fn native_label(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Zh => "简体中文",
            Self::Es => "Español",
            Self::Hi => "हिन्दी",
            Self::Fr => "Français",
            Self::Ru => "Русский",
        }
    }

    pub fn from_code(value: &str) -> Option<Self> {
        match value.trim().to_ascii_lowercase().as_str() {
            "en" => Some(Self::En),
            "zh" | "zh-cn" => Some(Self::Zh),
            "es" => Some(Self::Es),
            "hi" => Some(Self::Hi),
            "fr" => Some(Self::Fr),
            "ru" => Some(Self::Ru),
            _ => None,
        }
    }

    pub fn detect() -> Self {
        #[link(name = "kernel32")]
        extern "system" {
            fn GetUserDefaultUILanguage() -> u16;
        }
        let primary = unsafe { GetUserDefaultUILanguage() } & 0x03ff;
        match primary {
            0x04 => Self::Zh,
            0x0a => Self::Es,
            0x39 => Self::Hi,
            0x0c => Self::Fr,
            0x19 => Self::Ru,
            _ => Self::En,
        }
    }
}

