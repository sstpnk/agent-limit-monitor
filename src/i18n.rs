static CURRENT: AtomicU8 = AtomicU8::new(Lang::Ru as u8);

pub fn set(lang: Lang) {
    CURRENT.store(lang as u8, Ordering::Relaxed);
}

pub fn current() -> Lang {
    match CURRENT.load(Ordering::Relaxed) {
        1 => Lang::Zh,
        2 => Lang::Es,
        3 => Lang::Hi,
        4 => Lang::Fr,
        5 => Lang::Ru,
        _ => Lang::En,
    }
}

pub fn for_config(value: &str) -> Lang {
    if value.trim().is_empty() || value.eq_ignore_ascii_case("system") {
        Lang::detect()
    } else {
        Lang::from_code(value).unwrap_or_else(Lang::detect)
    }
}

pub fn s() -> &'static Strings {
    match current() {
        Lang::En => &EN,
        Lang::Zh => &ZH,
        Lang::Es => &ES,
        Lang::Hi => &HI,
        Lang::Fr => &FR,
        Lang::Ru => &RU,
    }
}

pub fn font_name() -> &'static str {
    match current() {
        Lang::Zh => "Microsoft YaHei UI",
        Lang::Hi => "Nirmala UI",
        _ => "Segoe UI Variable Text",
    }
}
